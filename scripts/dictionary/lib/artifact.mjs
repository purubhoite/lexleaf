/**
 * Writes the shipped dictionary artifact.
 *
 * Four files, all generated, none committed:
 *
 * - `entries.jsonl`     one JSON record per headword, in key order;
 * - `entries.idx`       the binary index described in
 *                       `src/core/dictionary/wordnet/binaryIndex.ts`;
 * - `morphology.json`   WordNet's exception lists;
 * - `manifest.json`     pinned release, licences, counts and checksums;
 * - `NOTICE.md`         the third-party notice, derived from the manifest.
 *
 * Determinism is a requirement, not an accident: keys are sorted by UTF-8
 * byte order, object fields are written in a fixed order, and nothing here
 * reads the clock, the locale, the filesystem's ordering or an absolute
 * path. Two builds of the same input produce byte-identical files, which
 * `verify-reproducible.mjs` checks.
 */

/* global Buffer */

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const INDEX_MAGIC = 'IPRD';
export const INDEX_VERSION = 1;
export const MANIFEST_FORMAT_VERSION = 1;

const HEADER_BYTES = 16;
const RECORD_BYTES = 16;

const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

/**
 * Encodes the payload and its index.
 *
 * @param {Map<string, { senses: object[], pr?: object[] }>} entries
 * @returns {{ payload: Buffer, index: Buffer, keys: string[] }}
 */
export const encodeEntries = (entries) => {
  const keys = [...entries.keys()].sort((left, right) =>
    Buffer.compare(Buffer.from(left, 'utf8'), Buffer.from(right, 'utf8')),
  );

  const payloads = [];
  const keyChunks = [];
  const records = [];

  let valueOffset = 0;
  let keyOffset = 0;

  for (const key of keys) {
    const entry = entries.get(key);
    // Field order fixed: senses, then pronunciations.
    const record = entry.pr === undefined ? { s: entry.senses } : { s: entry.senses, pr: entry.pr };
    const line = Buffer.from(`${JSON.stringify(record)}\n`, 'utf8');
    const keyBytes = Buffer.from(key, 'utf8');

    payloads.push(line);
    keyChunks.push(keyBytes);
    records.push({
      keyOffset,
      keyLength: keyBytes.length,
      valueOffset,
      valueLength: line.length - 1,
    });

    valueOffset += line.length;
    keyOffset += keyBytes.length;
  }

  const keyBlob = Buffer.concat(keyChunks);
  const header = Buffer.alloc(HEADER_BYTES);

  header.write(INDEX_MAGIC, 0, 'ascii');
  header.writeUInt32LE(INDEX_VERSION, 4);
  header.writeUInt32LE(records.length, 8);
  header.writeUInt32LE(keyBlob.length, 12);

  const table = Buffer.alloc(records.length * RECORD_BYTES);

  records.forEach((record, position) => {
    const at = position * RECORD_BYTES;

    table.writeUInt32LE(record.keyOffset, at);
    table.writeUInt32LE(record.keyLength, at + 4);
    table.writeUInt32LE(record.valueOffset, at + 8);
    table.writeUInt32LE(record.valueLength, at + 12);
  });

  return {
    payload: Buffer.concat(payloads),
    index: Buffer.concat([header, table, keyBlob]),
    keys,
  };
};

const notice = (manifest, licenceHeader) =>
  [
    '# Dictionary data — third-party notices',
    '',
    'This file is generated by `scripts/dictionary/build.mjs` from the manifest',
    'that accompanies the shipped dictionary artifact. Do not edit it by hand.',
    '',
    `## ${manifest.source.dataset} ${manifest.source.release}`,
    '',
    ...manifest.credits.map((credit) => `- ${credit}`),
    '',
    '### Licences',
    '',
    ...manifest.licences.map((licence) => `- ${licence.name} — ${licence.url}`),
    '',
    '### Modifications',
    '',
    manifest.modificationStatement,
    '',
    '### Pinned source',
    '',
    `- Archive: ${manifest.source.archiveUrl}`,
    `- Archive SHA-256: \`${manifest.source.archiveSha256}\``,
    '- Pronunciation data: excluded from the V1 production artifact.',
    `- Transform version: ${manifest.transformVersion}`,
    '',
    '### Generated files',
    '',
    ...manifest.files.map(
      (file) => `- \`${file.name}\` — ${String(file.bytes)} bytes, SHA-256 \`${file.sha256}\``,
    ),
    '',
    '### Licence text as distributed with the data',
    '',
    '```text',
    licenceHeader.replace(/\s+$/u, ''),
    '```',
    '',
    '### Legal status',
    '',
    'No legal review of this redistribution has been carried out. Commercial',
    'release requires one; see `docs/DICTIONARY_INVESTIGATION.md`.',
    '',
  ].join('\n');

/**
 * Writes every artifact file and returns the manifest that was written.
 *
 * @param {{
 *   outDir: string,
 *   entries: Map<string, { senses: object[], pr?: object[] }>,
 *   exceptions: object,
 *   source: object,
 *   licenceHeader: string,
 *   counts: Record<string, number>,
 * }} options
 */
export const writeArtifact = ({ outDir, entries, exceptions, source, licenceHeader, counts }) => {
  mkdirSync(outDir, { recursive: true });

  const { payload, index } = encodeEntries(entries);
  const morphology = Buffer.from(
    `${JSON.stringify({ version: 1, exceptions }, null, 0)}\n`,
    'utf8',
  );

  writeFileSync(join(outDir, 'entries.jsonl'), payload);
  writeFileSync(join(outDir, 'entries.idx'), index);
  writeFileSync(join(outDir, 'morphology.json'), morphology);

  const files = [
    { name: 'entries.jsonl', bytes: payload.length, sha256: sha256(payload) },
    { name: 'entries.idx', bytes: index.length, sha256: sha256(index) },
    { name: 'morphology.json', bytes: morphology.length, sha256: sha256(morphology) },
  ];

  const manifest = {
    formatVersion: MANIFEST_FORMAT_VERSION,
    transformVersion: source.transformVersion,
    source: {
      dataset: source.dataset,
      release: source.release,
      tag: source.tag,
      commit: source.commit,
      archiveUrl: source.archive.url,
      archiveSha256: source.archive.sha256,
      pronunciationExcluded: true,
    },
    licences: source.licences,
    modified: true,
    modificationStatement: source.modificationStatement,
    credits: source.credits,
    counts,
    files,
  };

  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

  writeFileSync(join(outDir, 'manifest.json'), manifestText, 'utf8');
  writeFileSync(join(outDir, 'NOTICE.md'), notice(manifest, licenceHeader), 'utf8');

  return {
    manifest,
    sizes: {
      'entries.jsonl': payload.length,
      'entries.idx': index.length,
      'morphology.json': morphology.length,
      'manifest.json': Buffer.byteLength(manifestText),
    },
  };
};

export { sha256 };
