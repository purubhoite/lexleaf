import type { ReactElement } from 'react';

import { Message } from '../../ui/Message';

import type { ExplainControl as ExplainControlState } from './useExplainInContext';

/**
 * The explanation control inside the definition popup.
 *
 * Presentational on purpose: it renders what the hook decided and reports
 * presses. Three things about it are deliberate and should not be
 * "improved" away:
 *
 * - **The disclosure is attached to the button, not hidden in settings.**
 *   A reader is told where this sentence would go *before* they press
 *   anything, every time, because that is the moment the decision is made.
 * - **The explanation is plain text in a paragraph.** Model output is
 *   untrusted content; it is never interpreted as markup, which is why
 *   there is no markdown renderer and no sanitizer anywhere near it.
 * - **It is secondary to the dictionary.** It sits below the definition,
 *   says "most likely sense" rather than "the meaning", and every failure
 *   leaves the definition untouched.
 */

export interface ExplainControlProps {
  readonly explain: ExplainControlState;
}

const destinationSentence = (provider: string, remote: boolean): string =>
  remote
    ? `Sends this sentence and this word to ${provider}.`
    : `Sends this sentence and this word to ${provider}, which runs on this computer.`;

export const ExplainControl = ({ explain }: ExplainControlProps): ReactElement | null => {
  if (explain.state === 'unsupported' || explain.destination === null) {
    // No provider is configured. There is no control, no disclosure and
    // nothing to explain: the reader sees the Milestone 4 popup.
    return null;
  }

  const busy = explain.state === 'pending' || explain.state === 'loading';
  const label =
    explain.state === 'failed' || explain.state === 'stale' ? 'Retry' : 'Explain in context';

  return (
    <section
      className="dictionary-popup__explain"
      aria-label="In-context explanation"
      data-testid="explain-control"
    >
      {explain.explanation !== null && (
        <div className="dictionary-popup__explanation" data-state={explain.state}>
          <h3 className="dictionary-popup__explanation-heading">Most likely sense here</h3>
          <p className="dictionary-popup__explanation-text" data-testid="explanation-text">
            {explain.explanation.text}
          </p>

          {explain.explanation.truncated && (
            <p className="dictionary-popup__explanation-note" data-testid="explanation-truncated">
              This explanation was cut short.
            </p>
          )}

          {explain.state === 'stale' && (
            <p className="dictionary-popup__explanation-note" data-testid="explanation-previous">
              Written for an earlier version of this passage.
            </p>
          )}

          <p className="dictionary-popup__explanation-origin">
            Generated by {explain.explanation.model}. It may be wrong; the definition above is not.
          </p>
        </div>
      )}

      {explain.state === 'loading' && (
        <Message kind="busy" className="dictionary-popup__status" testId="explanation-loading">
          Generating…
        </Message>
      )}

      {explain.state === 'failed' && explain.message !== null && (
        <Message
          kind="problem"
          className="dictionary-popup__explain-error"
          testId="explanation-error"
        >
          {explain.message}
        </Message>
      )}

      {busy ? (
        <button
          type="button"
          className="control dictionary-popup__explain-cancel"
          data-testid="explanation-cancel"
          onClick={explain.onCancel}
        >
          Stop
        </button>
      ) : (
        <button
          type="button"
          className="control dictionary-popup__explain-button"
          data-testid="explain-in-context"
          data-state={explain.state}
          onClick={explain.onExplain}
        >
          {label}
        </button>
      )}

      {/*
        Shown whenever the button is, including next to an explanation that
        is already there: pressing again sends the passage again.
      */}
      <p className="dictionary-popup__explain-disclosure" data-testid="explanation-disclosure">
        {destinationSentence(explain.destination.provider, explain.destination.remote)}
      </p>
    </section>
  );
};
